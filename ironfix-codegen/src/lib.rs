//! # IronFix Codegen
//!
//! Build-time code generation for the IronFix FIX protocol engine.
//!
//! This crate turns a loaded `ironfix_dictionary::Dictionary` into Rust
//! source, in two independent outputs:
//!
//! - **Data definitions** ([`CodeGenerator::generate`], the default): one
//!   `u32` constant per field tag, and one owned struct per message
//!   (including the fields its components contribute and a struct per
//!   repeating group entry). These structs carry no `FixMessage` or
//!   `FixField` implementation.
//! - **Views, enumerations and writers** ([`CodeGenerator::generate_views`],
//!   opt-in): an enumeration per field with declared values (an undeclared
//!   wire value reads as `Other(&[u8])`), static repeating-group layouts for
//!   `ironfix_dictionary`'s group reader, a borrowed `XxxView<'m, 'a>` per
//!   message over a decoded `ironfix_core::message::RawMessage` with typed
//!   accessors that check each value against the validator's grammar, and a
//!   writer per message that checks every value and then sends its body in
//!   XML order (an entry: its delimiter first) to a generated `Sink`: a
//!   `FnMut(u32, &[u8])` closure, or a target that frames LENGTH/DATA pairs
//!   itself. The generated code depends on `ironfix-core`, `rust_decimal`
//!   and `ironfix-dictionary` `^0.5` (it calls `GroupSet::field`,
//!   `GroupSet::with_level_tags` and `FieldType::is_valid_value`).
//!
//! In both, FIX `Price`, `Qty`, `Amt`, `PriceOffset`, `Percentage` and
//! `Float` fields are `rust_decimal::Decimal`, never `f64`. Adding the views
//! did not change the default output: it is generated by its own method.
//!
//! Nothing in the IronFix workspace consumes either output at run time: the
//! engine and the codec read fields by tag. The outputs are compile-tested
//! from golden files in this crate's tests, and the full views of the
//! embedded FIX 4.4, FIX 4.2 and FIXT 1.1 dictionaries by the unpublished
//! `ironfix-codegen-check` workspace crate, whose build script generates them
//! for the workspace lints.
//!
//! ## Usage
//!
//! Typically used in a `build.rs` script to generate code at compile time:
//!
//! ```no_run
//! use ironfix_codegen::CodeGenerator;
//! use ironfix_dictionary::Dictionary;
//!
//! # fn main() -> Result<(), Box<dyn std::error::Error>> {
//! let generator = CodeGenerator::new();
//! let dict = Dictionary::fix44()?;
//! std::fs::write("fix44.rs", generator.generate(dict)?)?;
//! std::fs::write("fix44_views.rs", generator.generate_views(dict)?)?;
//! # Ok(())
//! # }
//! ```
//!
//! Both files are written with `//` line comments rather than an inner `//!`
//! header, so each can be `include!`d inside a module.
//!
//! Generation **fails closed**: a dictionary that references a field or
//! component it does not define, or a component that contains itself, is a
//! [`GeneratorError`] rather than a struct silently missing a field.
//!
//! ## Limits of the views
//!
//! - **The views cover the message body.** Header and trailer fields are read
//!   from the `RawMessage` itself; header and trailer groups are part of each
//!   message's layout only so a body read skips them.
//! - **One dictionary.** The header, trailer and body come from the
//!   dictionary given. For a FIXT.1.1 session over a FIX 5.0 application
//!   dictionary, which carries no header, the generated layouts know no
//!   header group.
//! - **Members follow the XML order** the dictionary records (`members()`),
//!   a component's members in its place; within a group entry the delimiter
//!   is always written first. The default output keeps its own order
//!   (direct fields, component fields, groups), unchanged.

